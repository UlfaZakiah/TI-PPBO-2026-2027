//Mencetak biodata mahasiswa pada baris terpisah dan pada baris yang sama

public class BiodataSaya {
    public static void main(String[] args) {
        //Latihan 1: Mencetak Nama, NIM, dan Program Studi pada baris terpisah menggunakan println()
        System.out.println("Nama: Ulfa Zakiah");
        System.out.println("NIM: 2025573010065");
        System.out.println("Program Studi: Teknik Informatika");

        System.out.println(); // Baris pemisah

        // Latihan 2: Cetak Nama dan NIM pada baris yang sama dengan print()
        System.out.print("Nama: Ulfa Zakiah - ");
        System.out.print("NIM: 2025573010065\n");
        System.out.println("Program Studi: Teknik Informatika");
    }
}